import type { HttpRouter } from "convex/server";
import { internal } from "./_generated/api";
import { httpAction } from "./_generated/server";
import { OAUTH_CALLBACK_PATHS, type OAuthCallbackProvider, oauthCallbackUrl } from "./lib/oauthCallback";
import { generateOpaqueToken, hashOpaqueToken, isOpaqueToken, sha256Hex } from "./lib/oauthHandoff";
import { forwardedCallbackUrl, mintOAuthState, oauthStateConfigFromEnv, routeOAuthState } from "./lib/oauthState";
import { tokenCipherFromEnv, VIEWER_TOKEN_KEY } from "./lib/tokenCipher";
import {
  allowedReturnOrigins,
  VIEWER_PLATFORMS,
  type ViewerAuthErrorCode,
  type ViewerPlatform,
  type ViewerReturnTarget,
  viewerReturnTarget,
  viewerReturnUrl,
} from "./lib/viewerAuth";
import { checkEdgeGate } from "./lib/viewerEdgeGate";
import { viewerPlatformClient } from "./lib/viewerPlatforms";
import { viewerRateLimiter } from "./lib/viewerRateLimits";
import { logger } from "./logger";

// The redirect half of viewer sign-in (lib/viewerAuth.ts has the whole flow):
//
//   GET /api/viewer-auth/<platform>/start?return_to=<page URL>&nonce=<nonce>
//   GET /api/viewer-auth/<platform>/callback   (the platform's redirect URL)
//
// Pages never call the start route themselves: they go to the edge's
// `<user pages origin>/u/_/viewer-auth/<platform>/start`, which limits sign-in
// per client address and forwards here with the edge secret
// (lib/viewerEdgeGate.ts). A start without it is refused.
//
// The callback path must be registered as a redirect URL with the platform's
// app, as the streamer sign-in callback is.

/** Each platform's entry in OAUTH_CALLBACK_PATHS, whose paths are the registered redirect URLs. */
const CALLBACK_PROVIDERS: Record<ViewerPlatform, OAuthCallbackProvider> = {
  twitch: "viewerTwitch",
};

function startPath(platform: ViewerPlatform): string {
  return `/api/viewer-auth/${platform}/start`;
}

function redirect(location: string): Response {
  return new Response(null, { status: 302, headers: { Location: location } });
}

/** For a request with nowhere safe to send the browser back to. */
function refuse(status: number, message: string): Response {
  return new Response(message, { status, headers: { "Content-Type": "text/plain; charset=utf-8" } });
}

function failBack(target: ViewerReturnTarget, error: ViewerAuthErrorCode, detail: Record<string, unknown> = {}) {
  logger.warn("viewer sign-in failed", { error, ...detail });
  return redirect(viewerReturnUrl(target, { error }));
}

function startHandler(platform: ViewerPlatform) {
  return httpAction(async (ctx, request) => {
    const gate = await checkEdgeGate(request.headers, process.env);
    if (!gate.ok) {
      if (gate.refusal === "not_configured") {
        logger.error("refusing viewer sign-in: the edge gate is not configured", { problem: gate.problem });
        return refuse(500, "Viewer sign-in is not configured");
      }
      return refuse(401, "Viewer sign-in starts from the page");
    }
    const url = new URL(request.url);
    const allowed = allowedReturnOrigins(process.env.USER_PAGES_BASE_URL);
    const target = viewerReturnTarget(url.searchParams.get("return_to"), allowed);
    if (target === null) {
      return refuse(400, "return_to must be a page URL on an allowed origin");
    }
    const limit = await viewerRateLimiter.limit(ctx, "viewerLoginStart");
    if (!limit.ok) {
      return failBack(target, "rate_limited");
    }
    // Generated by the page that is signing in and kept there; the session is
    // issued only to whoever presents it again (viewerSession.exchangeHandoff).
    const nonce = url.searchParams.get("nonce");
    if (!isOpaqueToken(nonce)) {
      return failBack(target, "missing_params");
    }

    const state = await mintOAuthState(oauthStateConfigFromEnv());
    await ctx.runMutation(internal.viewerLogin.storeLoginState, {
      stateHash: await sha256Hex(state),
      platform,
      returnOrigin: target.origin,
      returnPath: target.path,
      nonceHash: await hashOpaqueToken(nonce),
    });
    const client = viewerPlatformClient(platform);
    return redirect(client.authorizeUrl(state, oauthCallbackUrl(CALLBACK_PROVIDERS[platform])));
  });
}

function callbackHandler(platform: ViewerPlatform) {
  return httpAction(async (ctx, request) => {
    const url = new URL(request.url);
    const state = url.searchParams.get("state");
    if (!state) {
      return refuse(400, "Missing sign-in state");
    }
    const route = await routeOAuthState(state, oauthStateConfigFromEnv());
    if (route.kind === "forward") {
      return redirect(forwardedCallbackUrl(route.origin, url));
    }
    if (route.kind === "invalid") {
      return refuse(400, "Invalid sign-in state");
    }
    const login = await ctx.runMutation(internal.viewerLogin.consumeLoginState, { stateHash: await sha256Hex(state) });
    if (login === null || login.platform !== platform) {
      return refuse(400, "This sign-in has expired or was already used. Start again from the page.");
    }
    // The allowlist can shrink while the viewer is on the consent page (a
    // custom domain removed); the state's origin is checked again before any
    // code is sent there.
    if (!allowedReturnOrigins(process.env.USER_PAGES_BASE_URL).includes(login.returnOrigin)) {
      return refuse(400, "This page can no longer sign viewers in");
    }
    const target: ViewerReturnTarget = { origin: login.returnOrigin, path: login.returnPath };

    const code = url.searchParams.get("code");
    if (!code) {
      // Platforms answer a declined consent with ?error=access_denied and no code.
      return failBack(target, url.searchParams.get("error") === "access_denied" ? "access_denied" : "missing_params");
    }

    const client = viewerPlatformClient(platform);
    const now = Date.now();
    const grant = await client.exchangeCode(code, oauthCallbackUrl(CALLBACK_PROVIDERS[platform]), now);
    if (!grant.ok) {
      return failBack(target, "token_exchange_failed", { platform });
    }
    const profile = await client.fetchProfile(grant.value.accessToken);
    if (!profile.ok) {
      return failBack(target, "profile_fetch_failed", { platform });
    }

    const viewerTokens = await tokenCipherFromEnv(VIEWER_TOKEN_KEY);
    const handoffCode = generateOpaqueToken();
    await ctx.runMutation(internal.viewerLogin.completeLogin, {
      platform,
      profile: profile.value,
      grant: {
        sealedAccessToken: await viewerTokens.seal(grant.value.accessToken),
        sealedRefreshToken: await viewerTokens.seal(grant.value.refreshToken),
        expiresAt: grant.value.expiresAt,
        scopes: grant.value.scopes,
      },
      origin: login.returnOrigin,
      nonceHash: login.nonceHash,
      codeHash: await hashOpaqueToken(handoffCode),
    });
    return redirect(viewerReturnUrl(target, { code: handoffCode }));
  });
}

/** Adds every viewer sign-in route to the deployment's router. */
export function registerViewerAuthRoutes(http: HttpRouter): void {
  for (const platform of VIEWER_PLATFORMS) {
    http.route({ path: startPath(platform), method: "GET", handler: startHandler(platform) });
    http.route({
      path: OAUTH_CALLBACK_PATHS[CALLBACK_PROVIDERS[platform]],
      method: "GET",
      handler: callbackHandler(platform),
    });
  }
}
